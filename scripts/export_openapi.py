"""Regenerate ``docs/openapi.json`` and the endpoint index of ``docs/API_CONTRACT.md``.

Run from the repository root after any change to an ``/api/*`` endpoint, an exposed Pydantic
model or the capability list::

    python scripts/export_openapi.py

``tests/test_openapi_contract.py`` fails when the committed files drift from the code.
"""

from __future__ import annotations

import json
import re
import tempfile
from pathlib import Path
from typing import Any

from app.core.settings import EnvSettings
from app.main import create_app

ROOT = Path(__file__).resolve().parent.parent
OPENAPI_PATH = ROOT / "docs" / "openapi.json"
CONTRACT_PATH = ROOT / "docs" / "API_CONTRACT.md"
BEGIN = "<!-- BEGIN ENDPOINTS (generated by scripts/export_openapi.py) -->"
END = "<!-- END ENDPOINTS -->"
METHODS = ("get", "post", "put", "patch", "delete")
REGENERATE = "python scripts/export_openapi.py"


def build_schema() -> dict[str, Any]:
    """The OpenAPI document of a default, isolated application (no environment leakage)."""
    with tempfile.TemporaryDirectory() as data_dir:
        settings = EnvSettings(
            _env_file=None,
            data_dir=Path(data_dir),
            root_path="",
            admin_password="",
            app_api_key="",
        )
        schema: dict[str, Any] = create_app(settings).openapi()
    # Round-trip so the result equals what ``json.loads`` of the exported file returns.
    return json.loads(json.dumps(schema))


def render_schema(schema: dict[str, Any]) -> str:
    """Canonical text of ``docs/openapi.json`` (sorted keys, stable, trailing newline)."""
    return json.dumps(schema, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def render_endpoints(schema: dict[str, Any]) -> str:
    """Markdown table of every operation, from the OpenAPI document."""
    rows = ["| Method | Path | Summary |", "| --- | --- | --- |"]
    for path in sorted(schema["paths"]):
        for method in METHODS:
            operation = schema["paths"][path].get(method)
            if operation:
                summary = str(operation.get("summary", "")).replace("|", chr(92) + "|")
                rows.append(f"| `{method.upper()}` | `{path}` | {summary} |")
    return "\n".join(rows)


def splice_endpoints(document: str, table: str) -> str:
    """``document`` with the generated block replaced by ``table``."""
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.DOTALL)
    if not pattern.search(document):
        raise ValueError(f"{CONTRACT_PATH.name} has no endpoint markers")
    return pattern.sub(lambda _: f"{BEGIN}\n\n{table}\n\n{END}", document)


def main() -> None:
    schema = build_schema()
    OPENAPI_PATH.write_text(render_schema(schema), encoding="utf-8", newline=chr(10))
    contract = CONTRACT_PATH.read_text(encoding="utf-8")
    CONTRACT_PATH.write_text(
        splice_endpoints(contract, render_endpoints(schema)), encoding="utf-8", newline="\n"
    )
    print(f"Wrote {OPENAPI_PATH.relative_to(ROOT)} and the endpoint index of {CONTRACT_PATH.name}")


if __name__ == "__main__":
    main()
